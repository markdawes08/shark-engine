MouseButton translate_glfw_mouse_button(int button) noexcept {
    switch (button) {
    case 0:
        return MouseButton::left;
    case 1:
        return MouseButton::right;
    case 2:
        return MouseButton::middle;
    case 3:
        return MouseButton::button_4;
    case 4:
        return MouseButton::button_5;
    case 5:
        return MouseButton::button_6;
    case 6:
        return MouseButton::button_7;
    case 7:
        return MouseButton::button_8;
    default:
        return MouseButton::unknown;
    }
}

std::optional<ButtonAction> translate_glfw_action(int action) noexcept {
    switch (action) {
    case 0:
        return ButtonAction::release;
    case 1:
        return ButtonAction::press;
    case 2:
        return ButtonAction::repeat;
    default:
        return std::nullopt;
    }
}

